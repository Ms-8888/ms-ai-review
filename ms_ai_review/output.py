from pathlib import Path

from ms_ai_review.tools import Finding

_SEVERITY_PREFIX = {
    "CRITICAL": "[CRITICAL]",
    "WARNING":  "[WARNING] ",
    "INFO":     "[INFO]    ",
}


def format_finding(f: Finding) -> str:
    prefix = _SEVERITY_PREFIX.get(f.severity, f"[{f.severity}]")
    lines = [f"{prefix} Line {f.line} — {f.message}"]
    if f.fix:
        lines.append(f"           Fix: {f.fix}")
    return "\n".join(lines)


def print_finding(f: Finding) -> None:
    print(format_finding(f))


def print_summary(findings: list[Finding], output_path: Path | None, filename: str) -> None:
    counts = {"CRITICAL": 0, "WARNING": 0, "INFO": 0}
    for f in findings:
        counts[f.severity] = counts.get(f.severity, 0) + 1

    parts = [f"{v} {k.lower()}" for k, v in counts.items() if v > 0]
    summary = ", ".join(parts) if parts else "no issues found"

    if not findings:
        print(f"\nNo issues found in {filename}.")
    else:
        saved = f" Full review saved to {output_path}" if output_path else ""
        print(f"\nSummary: {summary}.{saved}")


def write_markdown(findings: list[Finding], output_path: Path, filename: str, model: str) -> None:
    lines = [
        f"# Code Review: {filename}",
        "",
        f"Generated by [ms-ai-review](https://github.com/Ms-8888/ms-ai-review)",
        "",
        "---",
        "",
    ]

    if not findings:
        lines.append("No issues found.")
    else:
        for f in findings:
            prefix = _SEVERITY_PREFIX.get(f.severity, f.severity).strip()
            lines.append(f"**{prefix} Line {f.line} — {f.message}**")
            if f.fix:
                lines.append(f"**Fix:** {f.fix}")
            lines.append("")

        counts = {"CRITICAL": 0, "WARNING": 0, "INFO": 0}
        for f in findings:
            counts[f.severity] = counts.get(f.severity, 0) + 1
        parts = [f"{v} {k.lower()}" for k, v in counts.items() if v > 0]
        lines += [
            "---",
            "",
            f"**Summary:** {', '.join(parts)}",
            "",
            f"*Reviewed with {model} using streaming tool use + prompt caching*",
        ]

    output_path.write_text("\n".join(lines), encoding="utf-8")
